import { mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';
import { deploymentFromBroadcast, sanitizedBroadcast } from './deployments.ts';

const root = fileURLToPath(new URL('../', import.meta.url));
const names = ['BatchAuction', 'DemoToken', 'Faucet'] as const;
const output = ['// Generated by pnpm gen from Foundry artifacts. Do not edit.'];
for (const name of names) {
  const artifact: { abi?: unknown[] } = JSON.parse(
    await readFile(resolve(root, 'contracts/out', `${name}.sol`, `${name}.json`), 'utf8')
  );
  if (!Array.isArray(artifact.abi)) throw new Error(`Missing ABI: ${name}. Run forge build first.`);
  output.push(`export const ${name[0]!.toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;`);
}
await writeFile(resolve(root, 'packages/core/src/abi.ts'), output.join('\n\n') + '\n');
console.log(`Generated ${names.join(', ')} ABIs.`);

// Preserve other networks; dry-run broadcasts are never deployment evidence.
const deploymentLines: string[] = [];
for (const chainId of [143, 10143]) {
  const file = resolve(root, 'contracts/broadcast/Deploy.s.sol', String(chainId), 'run-latest.json');
  try {
    const data = JSON.parse(await readFile(file, 'utf8'));
    const deployment = deploymentFromBroadcast(data, chainId);
    await mkdir(resolve(root, 'deployments'), { recursive: true });
    await writeFile(resolve(root, 'deployments', `${chainId}.json`), JSON.stringify(sanitizedBroadcast(data, chainId), null, 2) + '\n');
    deploymentLines.push(`  ${chainId}: ${JSON.stringify(deployment)},`);
  } catch (error) {
    if ((error as NodeJS.ErrnoException).code !== 'ENOENT') throw error;
    // A sanitized record retains confirmed addresses when ignored broadcast files are absent in CI.
    try {
      const record = JSON.parse(await readFile(resolve(root, 'deployments', `${chainId}.json`), 'utf8'));
      const deployment = deploymentFromBroadcast(record, chainId);
      deploymentLines.push(`  ${chainId}: ${JSON.stringify(deployment)},`);
    } catch (missing) {
      if ((missing as NodeJS.ErrnoException).code !== 'ENOENT') throw missing;
      deploymentLines.push(`  ${chainId}: null,`);
    }
  }
}
await writeFile(resolve(root, 'packages/core/src/addresses.ts'), `// Generated by pnpm gen from successful Deploy.s.sol receipts.\nimport type { Address } from 'viem';\nexport type ChainId = 143 | 10143;\nexport interface Deployment { market: Address; faucet: Address; base: Address; quote: Address; startBlock: string; hashes: string[] }\nexport const addresses: Record<ChainId, Deployment | null> = {\n${deploymentLines.join('\n')}\n};\n`);
