import { readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import { resolve } from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const names = ['BatchAuction', 'DemoToken', 'Faucet'] as const;
const output = ['// Generated by pnpm gen from Foundry artifacts. Do not edit.'];
for (const name of names) {
  const artifact: { abi?: unknown[] } = JSON.parse(
    await readFile(resolve(root, 'contracts/out', `${name}.sol`, `${name}.json`), 'utf8')
  );
  if (!Array.isArray(artifact.abi)) throw new Error(`Missing ABI: ${name}. Run forge build first.`);
  output.push(`export const ${name[0]!.toLowerCase()}${name.slice(1)}Abi = ${JSON.stringify(artifact.abi, null, 2)} as const;`);
}
await writeFile(resolve(root, 'packages/core/src/abi.ts'), output.join('\n\n') + '\n');
console.log(`Generated ${names.join(', ')} ABIs.`);
