#!/usr/bin/env python3
"""Cold production-call gas under identical bytecode and two Monad hardforks."""
import argparse
import datetime
import hashlib
import json
import os
from pathlib import Path
import re
import subprocess

ROOT = Path(__file__).resolve().parents[1]
CONTRACTS = ROOT / 'contracts'
OUT = CONTRACTS / 'bench/out'
FORGE = str(ROOT / '.tools/foundry/bin/forge') if (ROOT / '.tools/foundry/bin/forge').exists() else 'forge'
ENTRYPOINTS = ['place', 'placeSelfClear', 'placeManySelfClear', 'placeForSelfClear', 'cancel', 'claim1', 'claim50', 'clear', 'drip', 'withdraw']

def generate_scattered():
    source = (CONTRACTS / 'src/BatchAuction.sol').read_text()
    source = source.replace('contract BatchAuction is', 'contract BatchAuctionScattered is')
    source = source.replace('from "./lib/', 'from "../../src/lib/')
    for side in ['bid', 'ask']:
        source = source.replace(f'uint256[256] private {side}Ticks;', f'mapping(uint16 => uint256) private {side}Ticks;')
        for origin in ['lo', 'from']:
            source = source.replace(f'{side}Ticks[uint256({origin}) + j]', f'{side}Ticks[uint16(uint256({origin}) + j)]')
    source = source.replace('uint256[256] storage ticks', 'mapping(uint16 => uint256) storage ticks')
    source = source.replace('let b := sload(add(bidTicks.slot, add(lo, j)))',
        'mstore(0, add(lo, j))\n                    mstore(32, bidTicks.slot)\n                    let b := sload(keccak256(0, 64))')
    source = source.replace('let a := sload(add(askTicks.slot, add(lo, j)))',
        'mstore(32, askTicks.slot)\n                    let a := sload(keccak256(0, 64))')
    target = CONTRACTS / 'bench/generated/BatchAuctionScattered.sol'
    target.parent.mkdir(exist_ok=True)
    target.write_text('// Generated by scripts/clear-bench.py; never deploy.\n' + source)


def run(args, profile='default'):
    result = subprocess.run([FORGE, *args], cwd=CONTRACTS, env=dict(os.environ, FOUNDRY_PROFILE=profile),
                            text=True, capture_output=True)
    if result.returncode:
        raise RuntimeError(result.stdout + result.stderr)
    return result.stdout


def parse(raw, historical=False):
    measurements = {}
    for line in re.findall(r'^\s*BENCH_JSON (\{.*\})\s*$', raw, re.MULTILINE):
        row = json.loads(line)
        assert row['name'] not in measurements, 'Duplicate benchmark'
        assert row['gas'] > 0
        measurements[row['name']] = row
    required = {'clear8', 'clear32', 'clear128', 'clear256', 'mapping8', 'mapping32', 'mapping128', 'mapping256',
                'orders10', 'orders100', 'orders1000', *ENTRYPOINTS}
    if historical: required.discard('withdraw')
    assert required <= measurements.keys(), f'Missing benchmarks: {required - measurements.keys()}'
    return measurements


def buffered(gas):
    # ceil(gas * 1.075 / 1000) * 1000, with integer arithmetic only.
    return ((gas * 1075 + 999999) // 1000000) * 1000


def write_json(path, value):
    path.write_text(json.dumps(value, indent=2) + '\n')


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument('--generate-only', action='store_true')
    args = parser.parse_args()
    generate_scattered()
    run(['fmt', 'bench/generated/BatchAuctionScattered.sol'])
    if args.generate_only:
        return
    OUT.mkdir(parents=True, exist_ok=True)
    profiles = {}
    hashes = []
    for profile, fork in [('default', 'MonadTen'), ('pre_mip8', 'MonadNine')]:
        config = json.loads(run(['config', '--json'], profile))
        assert config['network'].lower() == 'monad'
        assert config['hardfork'] == f'monad:{fork}'
        assert config['isolate'] is True, 'Require fresh transaction access sets'
        repeats = []
        for repetition in range(2):
            raw = run(['test', '--match-contract', 'ClearBenchTest', '--gas-limit', '100000000', '--isolate', '-vv'], profile)
            (OUT / f'clear-{profile}-{repetition + 1}.log').write_text(raw)
            repeats.append(parse(raw))
        assert repeats[0] == repeats[1], f'{fork} is not reproducible'
        artifact = json.loads((CONTRACTS / 'out/BatchAuction.sol/BatchAuction.json').read_text())
        digest = hashlib.sha256(bytes.fromhex(artifact['deployedBytecode']['object'].removeprefix('0x'))).hexdigest()
        hashes.append(digest)
        profiles[fork] = {'runtimeBytecodeSha256': digest, 'measurements': repeats[0], 'reproducible': True}
        print(f'{fork}: {len(repeats[0])} measurements reproduced exactly', flush=True)
    assert hashes[0] == hashes[1], 'Production bytecode differs between hardforks'
    nine, ten = profiles['MonadNine']['measurements'], profiles['MonadTen']['measurements']
    names = ['clear8', 'clear32', 'clear128', 'clear256', 'orders10', 'orders100', 'orders1000']
    scenarios = [dict(name=name, activeTicks=ten[name]['activeTicks'], orders=ten[name]['orders'],
        scanTicks=int(name[5:]) if name.startswith('clear') else 32,
        monadNine=nine[name]['gas'], monadTen=ten[name]['gas'], ratio=nine[name]['gas'] / ten[name]['gas']) for name in names]
    ratio = nine['clear256']['gas'] / ten['clear256']['gas']
    variation = {}
    for fork, rows in [('MonadNine', nine), ('MonadTen', ten)]:
        costs = [rows[f'orders{count}']['gas'] for count in (10, 100, 1000)]
        variation[fork] = (max(costs) - min(costs)) / min(costs)
    assert ratio >= 10, f'Full-range ratio {ratio:.4f} below 10x'
    assert all(v < 0.05 for v in variation.values()), 'Clearing depends on order count'
    bounds = {name: buffered(max(row['gas'] for key, row in ten.items() if key == name or key.startswith(name + ':'))) for name in ENTRYPOINTS}
    assert all(0 < limit <= 30_000_000 for limit in bounds.values()), 'Operational limit exceeds transaction cap'
    extras = {}
    for key, row in ten.items():
        if not key.startswith('tooling:'):
            continue
        gas = row['gas']
        if key.startswith('tooling:deploy'):
            contract = 'DemoToken' if key.endswith(('Base', 'Quote')) else 'BatchAuction' if key.endswith('Market') else 'Faucet'
            artifact = json.loads((CONTRACTS / f'out/{contract}.sol/{contract}.json').read_text())
            # Conservative nonzero calldata cost for initcode + constructor args.
            # Harness creation already includes CREATE and initcode word costs.
            gas += 16 * (len(artifact['bytecode']['object'].removeprefix('0x')) // 2 + 512)
        extras[key] = buffered(gas)
    baseline = {}
    for fork, suffix in [('MonadTen', 'ten'), ('MonadNine', 'nine')]:
        path = OUT / f'clear-baseline-{suffix}.log'
        if path.exists():
            baseline[fork] = parse(path.read_text(), historical=True)
    evidence = {'generatedAt': datetime.datetime.now(datetime.timezone.utc).isoformat(),
        'foundryVersion': run(['--version']).strip(), 'seed': 42,
        'measurement': {'clearing': 'Production Result.clearGas around _clear; excludes telemetry/event and transaction intrinsic gas',
            'entrypoints': 'Isolated callee gas before refunds plus 21000 and exact 4/16 calldata intrinsic gas',
            'setup': 'Gas metering paused for book setup only; resumed before every measured production call',
            'orderCount': 'Identical 500 lots per side at two occupied ticks spanning 32 scanned ticks; 10 orders cannot populate 32 ticks per side'},
        'scenarios': scenarios,
        'ablation': [{'activeTicks': n, 'monadTenContiguous': ten[f'clear{n}']['gas'],
            'monadTenMapping': ten[f'mapping{n}']['gas'], 'ratio': ten[f'mapping{n}']['gas'] / ten[f'clear{n}']['gas']} for n in (8,32,128,256)],
        'entrypoints': {name: {'measuredWorst': max(row['gas'] for key, row in ten.items() if key == name or key.startswith(name + ':')), 'limit': bounds[name]} for name in ENTRYPOINTS},
        'profiles': profiles, 'acceptance': {'sameBytecode': True, 'reproducible': True, 'fullRangeRatio': ratio,
            'orderCountVariation': variation, 'liveTestnet': 'pending'},
        'optimization': {'before': baseline, 'after': {'MonadNine': nine['clear256']['gas'], 'MonadTen': ten['clear256']['gas']},
            'changes': ['Cache batch tag and copy tagged ladder with bounded memory-safe loop', 'Reuse candidates and bounded memory-safe auction loops', 'Pack Result into exactly two storage writes']},
        'toolingGas': extras}
    live_path = OUT / 'clear-live-testnet.json'
    live = json.loads(live_path.read_text()) if live_path.exists() else {}
    valid_live = live.get('benchmarkHash') == hashes[0] and live.get('status') == 'passed'
    evidence['liveTestnet'] = {'status': 'passed' if valid_live else 'pending',
        'local': live.get('parity', {}).get('local', 0) if valid_live else 0,
        'live': live.get('parity', {}).get('live', 0) if valid_live else 0,
        'relativeDifference': live.get('parity', {}).get('relativeDifference', 0) if valid_live else 0,
        'hash': live.get('parity', {}).get('hash', '') if valid_live else '',
        'market': live.get('addresses', {}).get('market', '') if valid_live else ''}
    evidence['acceptance']['liveTestnet'] = evidence['liveTestnet']['status']
    write_json(ROOT / 'packages/core/src/bench.json', evidence)
    write_json(ROOT / 'packages/core/src/gas.json', bounds)
    write_json(OUT / 'clear-summary.json', evidence)
    from monad_report import write_report
    write_report(evidence, ROOT)
    print(f"Full range {nine['clear256']['gas']:,} -> {ten['clear256']['gas']:,} ({ratio:.3f}x); placeSelfClear limit {bounds['placeSelfClear']:,}")


if __name__ == '__main__':
    main()
